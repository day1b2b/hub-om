// 화면에 보여 줄 자유 입력값에서 국내 주소를 가린다.
//
// 강사 위키 "조건 → 특이사항"(노션 "강사료 특이사항")에 강사 자택 주소가 들어 있는 경우가 있어,
// 보여 줄 때만 가린다. 저장 단계 가림(instructorNotePii.ts)은 동기화 정합성 테스트가 체크섬으로
// 고정해 둔 정책이라 건드리지 않는다. 원문은 노션에 남는다.

// 시·도 이름으로 시작해 60자 안에 "○○로 12", "○○길 3", "○○동 45-6" 같은 번지가 붙는 덩어리.
// 시·도 이름만 있고 번지가 없으면("경기 남부 출강 선호") 주소로 보지 않는다. 뒤의 번길·동·호·층까지 함께 가린다.
const ADDRESS = new RegExp(
  "(?:서울|부산|대구|인천|광주|대전|울산|세종|경기|강원|충청|충북|충남|전라|전북|전남|경상|경북|경남|제주)" +
    "[가-힣0-9\\s,.·-]{0,60}?(?:로|길|동|리|가)\\s*\\d+(?:-\\d+)?" +
    "(?:\\s*번?길\\s*\\d+(?:-\\d+)?)?" +
    "(?:[,\\s]*\\d+(?:동|호|층))*",
  "g"
);

export const ADDRESS_MASK = "[주소 비공개]";

/** 문장 속 주소만 "[주소 비공개]"로 바꾼다. 나머지 문장은 그대로 둔다. */
export function maskAddresses(value: string): string {
  return value.replace(ADDRESS, ADDRESS_MASK);
}
